import assert from 'node:assert/strict';
import { createHistory, historyShortcut } from '../../client/history.js';
let models=[{id:'one',width:480,preset:'custom'}],selection=['one'],camera=80,theme='light';
const capture=()=>({models:structuredClone(models),selection:[...selection]});
const history=createHistory(capture,snapshot=>{models=structuredClone(snapshot.models);selection=[...snapshot.selection];},2);
const edit=change=>{const before=history.checkpoint();change();return history.commit(before);};
assert.equal(history.canUndo,false);
edit(()=>{models[0].width=600;});
edit(()=>{models[0].preset='desktop';});
camera=125;theme='dark';
assert.equal(edit(()=>{selection=[];}),false,'Selection alone is not an edit and does not clear redo');
assert.equal(history.undo(),true);assert.equal(models[0].preset,'custom');
assert.equal(camera,125);assert.equal(theme,'dark','History never restores appearance/camera');
assert.equal(history.redo(),true);assert.equal(models[0].preset,'desktop');
history.undo();edit(()=>{models.push({id:'copy',width:600,preset:'custom'});});
assert.equal(history.canRedo,false,'A new document edit clears the redo branch');
history.undo();assert.equal(models.length,1);history.redo();assert.equal(models.length,2);
edit(()=>{models.splice(0,1);});history.undo();assert.equal(models.length,2);
history.undo();assert.equal(models.length,1);assert.equal(history.undo(),false,'Old snapshots are bounded');
assert.equal(historyShortcut({key:'z',metaKey:true}),'undo');
assert.equal(historyShortcut({key:'Z',metaKey:true,shiftKey:true}),'redo');
assert.equal(historyShortcut({key:'y',ctrlKey:true}),'redo');
assert.equal(historyShortcut({key:'z',ctrlKey:true,altKey:true}),null);
console.log('PASS canvas document history: resize/preset, duplicate/delete, exclusions, branching, bounded stack, shortcuts');
